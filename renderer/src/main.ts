import MarkdownIt from 'markdown-it';
import { katex as katexPlugin } from '@mdit/plugin-katex';
import katex from 'katex';
import DOMPurify from 'dompurify';
import 'katex/dist/katex.min.css';
import './styles.css';

type Kind = 'markdown' | 'svg' | 'latex';
type Theme = 'system' | 'light' | 'dark';
interface PreviewUpdate { kind: Kind; source: string; theme: Theme }
const host = document.getElementById('preview');
if (!host) throw new Error('missing preview root');

// HTML is disabled at the parser level. Markdown SVG fences are handled only by
// the separate SVG sanitizer below; remote images are also disabled by CSP.
const md = new MarkdownIt({ html: false, linkify: false, typographer: false });
md.use(katexPlugin, {
  delimiters: 'all',
  mathFence: true,
  trust: false,
  throwOnError: false,
  maxSize: 100,
  maxExpand: 1000,
  strict: 'warn'
});
md.renderer.rules.image = (tokens, idx) => {
  const alt = tokens[idx].content || '图片';
  return `<span title="已禁用外部图片">[图片：${md.utils.escapeHtml(alt)}]</span>`;
};
const defaultFence = md.renderer.rules.fence!;
md.renderer.rules.fence = (tokens, idx, options, env, renderer) => {
  const info = tokens[idx].info.trim().split(/\s+/)[0]?.toLowerCase();
  if (info === 'svg') return `<section class="svg-canvas">${sanitizeSvg(tokens[idx].content)}</section>`;
  return defaultFence(tokens, idx, options, env, renderer);
};

// Pure SVG graphics only. Scripts, links, external resources, animations and
// foreignObject are excluded; DOMPurify additionally sanitizes the SVG namespace.
function sanitizeSvg(source: string): string {
  if (!DOMPurify.isSupported) return '<p class="error">当前浏览器无法安全渲染 SVG</p>';
  const parsed = new DOMParser().parseFromString(source, 'image/svg+xml');
  if (parsed.documentElement.localName.toLowerCase() !== 'svg' || parsed.querySelector('parsererror')) {
    return '<p class="error">SVG 文档格式错误</p>';
  }
  const clean = DOMPurify.sanitize(source, {
    USE_PROFILES: { svg: true, svgFilters: true },
    FORBID_TAGS: ['script','foreignObject','style','a','image','animate','animateMotion','animateTransform','set','iframe'],
    FORBID_ATTR: ['href','xlink:href','style','src','srcset','onload','onclick'],
    SANITIZE_NAMED_PROPS: true,
    KEEP_CONTENT: false
  });
  // Fail closed if purification stripped the document or a non-SVG root survived.
  if (!/^\s*<svg(?:\s|>)/i.test(clean)) return '<p class="error">SVG 内容未通过安全检查</p>';
  return clean;
}

function renderLatex(source: string): string {
  if (/\\(?:documentclass|usepackage|begin\s*\{document\})/.test(source)) {
    return '<p class="error">当前支持 TeX 数学公式（含环境），尚未集成完整 LaTeX 文档编译器。</p>';
  }
  let formula = source.trim();
  if (formula.startsWith('$$') && formula.endsWith('$$')) formula = formula.slice(2, -2);
  if (formula.startsWith('\\[') && formula.endsWith('\\]')) formula = formula.slice(2, -2);
  try {
    return `<div class="math-canvas">${katex.renderToString(formula, {
      displayMode: true, throwOnError: false, trust: false,
      strict: 'warn', maxSize: 100, maxExpand: 1000, output: 'htmlAndMathml'
    })}</div>`;
  } catch {
    return '<p class="error">公式渲染失败，请检查数学语法。</p>';
  }
}

function render(update: PreviewUpdate): void {
  if (!['system','light','dark'].includes(update.theme)) return;
  if (!['markdown','svg','latex'].includes(update.kind)) return;
  if (typeof update.source !== 'string') return;
  document.documentElement.removeAttribute('data-theme');
  if (update.theme !== 'system') document.documentElement.dataset.theme = update.theme;
  // Treat any source as untrusted. Only sanitized markup can reach innerHTML.
  if (!DOMPurify.isSupported) {
    host!.textContent = '当前浏览器不支持安全渲染';
    return;
  }
  if (!update.source.trim()) {
    host!.replaceChildren();
    const empty = document.createElement('p');
    empty.className = 'placeholder';
    empty.textContent = '内容将在这里预览';
    host!.append(empty);
    return;
  }
  let html: string;
  switch (update.kind) {
    case 'svg': html = `<section class="svg-canvas">${sanitizeSvg(update.source)}</section>`; break;
    case 'latex': html = renderLatex(update.source); break;
    case 'markdown': {
      try { html = md.render(update.source); }
      catch { html = '<p class="error">Markdown 排版失败，请检查文稿。</p>'; }
      break;
    }
  }
  // KaTeX output contains trusted HTML+MathML generated by KaTeX. DOMPurify
  // removes any other scriptable/foreign content in the final document.
  host!.innerHTML = DOMPurify.sanitize(html, {
    USE_PROFILES: { html: true, svg: true, svgFilters: true, mathMl: true },
    FORBID_TAGS: ['script','iframe','object','embed','foreignObject','style','video','audio','form','image'],
    // Keep KaTeX-generated style attributes: they are necessary for correct math layout.
    // Source SVG style attrs were removed by sanitizeSvg before reaching here.
    FORBID_ATTR: ['src','srcset','href','xlink:href','target','formaction'],
    SANITIZE_NAMED_PROPS: true
  });
}

// Native-to-Web one-way data path. The renderer cannot call native APIs.
// No dynamic eval, window interface exposure to untrusted HTML or network access.
const api = Object.freeze({ update: (data: PreviewUpdate) => render(data) });
Object.defineProperty(window, 'MarknotePreview', { value: api, writable: false, configurable: false });
render({ kind: 'markdown', source: '', theme: 'system' });
